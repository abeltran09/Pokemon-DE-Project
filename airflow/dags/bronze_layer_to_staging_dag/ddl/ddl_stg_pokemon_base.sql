CREATE TABLE IF NOT EXISTS staging.stg_pokemon_base (
    pokemon_id INT PRIMARY KEY,
    name TEXT,
    height INT,
    weight INT,
    base_experience INT,
    type_1 TEXT,
    type_2 TEXT,
    hp INT,
    attack INT,
    defense INT,
    special_attack INT,
    special_defense INT,
    speed INT,
    sprite_url TEXT,
    bronze_batch_id VARCHAR(50),
    ingested_at TIMESTAMP,
    source_url TEXT,
    ingestion_date DATE,
    bronze_processed_at TIMESTAMP,
    source_file TEXT,
    staging_batch_id VARCHAR(50) NOT NULL,
    loaded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);